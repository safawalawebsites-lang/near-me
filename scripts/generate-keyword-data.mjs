import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const sourcePath = process.argv[2];
if (!sourcePath) {
  throw new Error("Usage: node scripts/generate-keyword-data.mjs /path/to/keywords.csv");
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let value = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (character === '"') {
      if (quoted && text[index + 1] === '"') {
        value += '"';
        index += 1;
      } else {
        quoted = !quoted;
      }
    } else if (character === "," && !quoted) {
      row.push(value);
      value = "";
    } else if ((character === "\n" || character === "\r") && !quoted) {
      if (character === "\r" && text[index + 1] === "\n") index += 1;
      row.push(value);
      if (row.some((cell) => cell.trim())) rows.push(row);
      row = [];
      value = "";
    } else {
      value += character;
    }
  }

  if (value || row.length) {
    row.push(value);
    rows.push(row);
  }
  return rows;
}

function slugify(value) {
  return value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

const projectRoot = resolve(import.meta.dirname, "..");
const rawDestination = resolve(projectRoot, "data/safawala-keywords.csv");
const generatedDestination = resolve(projectRoot, "app/keyword-data.generated.ts");
const parsed = parseCsv(readFileSync(sourcePath, "utf8"));
const [header, ...body] = parsed;

if (header.join(",") !== "No.,Category,Keyword") {
  throw new Error(`Unexpected CSV header: ${header.join(",")}`);
}

const seenKeywords = new Set();
const seenSlugs = new Set();
const keywords = body.map(([number, category, keyword], index) => {
  const normalizedKeyword = keyword.trim().replace(/\s+/g, " ");
  const slug = slugify(normalizedKeyword);
  if (!number || !category?.trim() || !normalizedKeyword || !slug) {
    throw new Error(`Invalid keyword row ${index + 2}`);
  }
  if (seenKeywords.has(normalizedKeyword.toLowerCase())) {
    throw new Error(`Duplicate keyword: ${normalizedKeyword}`);
  }
  if (seenSlugs.has(slug)) {
    throw new Error(`Duplicate slug: ${slug}`);
  }
  seenKeywords.add(normalizedKeyword.toLowerCase());
  seenSlugs.add(slug);
  return { id: Number(number), category: category.trim(), keyword: normalizedKeyword, slug };
});

mkdirSync(dirname(rawDestination), { recursive: true });
copyFileSync(sourcePath, rawDestination);
writeFileSync(
  generatedDestination,
  `// Generated by scripts/generate-keyword-data.mjs. Do not edit manually.\n` +
    `export type KeywordPageItem = { id: number; category: string; keyword: string; slug: string };\n\n` +
    `export const keywordPages: KeywordPageItem[] = ${JSON.stringify(keywords, null, 2)};\n\n` +
    `export const keywordCategories = [...new Set(keywordPages.map((item) => item.category))];\n`,
);

console.log(`Generated ${keywords.length} keyword pages across ${new Set(keywords.map((item) => item.category)).size} categories.`);
